import type { Contribution } from '@microteia/sdk';
import { documentTemplateContribution } from '@microteia/sdk';
import { RECEIPT_TEMPLATE } from './appointments';
import { APPOINTMENT_ITEMS, APPOINTMENTS, label, PETS, sourceIdOf, VACCINATIONS } from './collections';

/**
 * Documents generated from a record — data, not code. What sits between `{{ }}` is a field expression
 * (`{{customer.name}}` follows the reference); `{{#each}}` repeats the child records a dataset brings.
 *
 * - The **vaccination card** is generated from a pet ("Generate document" on the pet), every dose in order.
 * - The **receipt** is generated by the Finish button of an appointment, attached to it and shared with the
 *   owner in the portal.
 *
 * The text is written in English, the source language. The shop translates or redesigns it in its own
 * copy ("Customize" in Document templates), which then wins over this one.
 */

export const VACCINATION_CARD_TEMPLATE = 'pet-vaccination-card';

export const VACCINATION_CARD = `# Vaccination card

**Pet:** {{name}}{{#if breed}} — {{breed.name}}{{/if}}
**Owner:** {{customer.name}}{{#if customer.phone}} — {{customer.phone}}{{/if}}
{{#if birthDate}}**Born:** {{formatDate(birthDate, "DD/MM/YYYY")}}
{{/if}}{{#if currentWeightKg}}**Weight:** {{currentWeightKg}} kg on {{formatDate(weighedOn, "DD/MM/YYYY")}}
{{/if}}
| Vaccine | Batch | Applied on | Applied by | Next dose |
|---|---|---|---|---|
{{#each doses}}| {{vaccine.name}} | {{batch.lotNumber}} | {{formatDate(appliedOn, "DD/MM/YYYY")}} | {{veterinarian}} | {{#if nextDoseOn}}{{formatDate(nextDoseOn, "DD/MM/YYYY")}}{{/if}} |
{{/each}}

Issued on {{formatDate(today(), "DD/MM/YYYY")}}.
`;

export const RECEIPT = `# Receipt

**Appointment:** {{number}} — {{formatDate(scheduledOn, "DD/MM/YYYY")}} {{time}}
**Pet:** {{pet.name}}
**Owner:** {{pet.customer.name}}
{{#if groomer}}**Groomer:** {{groomer}}
{{/if}}
| Service | Price |
|---|--:|
{{#each lines}}| {{service.name}}{{#if package}} (package){{/if}} | {{formatMoney(price)}} |
{{/each}}

**Total:** {{formatMoney(total)}}

Thank you for trusting us with {{pet.name}}.
`;

export const DOCUMENT_CONTRIBUTIONS: Contribution[] = [
  documentTemplateContribution({
    key: VACCINATION_CARD_TEMPLATE,
    title: label('template.vaccination-card'),
    collection: PETS,
    screenSourceId: sourceIdOf(PETS),
    format: 'markdown',
    body: VACCINATION_CARD,
    fileName: 'Vaccination card - {{name}}',
    datasets: [
      {
        name: 'doses',
        from: VACCINATIONS,
        fromSourceId: sourceIdOf(VACCINATIONS),
        via: 'pet',
        orderBy: [{ path: 'appliedOn', dir: 'asc' }, { path: 'createdAt', dir: 'asc' }],
        limit: 100,
      },
    ],
  }),
  documentTemplateContribution({
    key: RECEIPT_TEMPLATE,
    title: label('template.receipt'),
    collection: APPOINTMENTS,
    screenSourceId: sourceIdOf(APPOINTMENTS),
    format: 'markdown',
    body: RECEIPT,
    fileName: 'Receipt {{number}} - {{pet.name}}',
    datasets: [
      { name: 'lines', from: APPOINTMENT_ITEMS, fromSourceId: sourceIdOf(APPOINTMENT_ITEMS), via: 'appointment', orderBy: [{ path: 'createdAt', dir: 'asc' }] },
    ],
  }),
];
